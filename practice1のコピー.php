// 数字を奇数か偶数か判別する関数を作成します。条件のもと処理を記述しましょう。
// 関数名は、distinguishNum という名前で定義してください。
// 引数として受け取った数字が奇数だったら、「〜は奇数です。」という文字列を返してください。
// 引数として受け取った数字が偶数だったら、「〜は偶数です。」という文字列を返してください。
// 奇数と偶数それぞれを渡して実行して、返り値を表示してください。

function distinguishNum($num)
{
    if ($num % 2 === 0) {
        echo $num.'は偶数です。';
    } else {
        echo $num.'は奇数です。';
    }
}
