// Q13 関数とswitch文
// switch文を使用して、成績の評価を出し分ける関数を作成します。下記の条件に沿って処理を記述してください。
// 関数名は、evaluateGrade という名前で定義してください。
// swtich文を使って引数で受け取った成績(文字列)に応じて処理を分けてください。
// 成績が、A か B だったら「合格です。」という文字列を返す。
// 成績が、C だったら「合格ですが追加課題があります。」という文字列を返す。
// 成績が、D だったら「不合格です。」という文字列を返す。
// その他の文字列だった場合は、「判定不明です。講師に問い合わせてください。」という文字列を返す。
// evaluateGrade関数に任意の引数を渡して実行して、結果を2種類表示してください。
function evaluateGrade($grade)
{
    switch ($grade) {
        case 'A':
        case 'B':// caseは複数まとめて書くことも可能
            echo '合格です。'."\n";
            break;

        case 'C':
            echo '合格ですが追加課題があります。'."\n";
            break;

        case 'D':
            echo '不合格です。'."\n";
            break;

        default:
            // 条件が全てfalseだった時の処理
            echo '判定不明です。講師に問い合わせてください。'."\n";
            break;
    }
}
evaluateGrade('C');
evaluateGrade('c');// 小文字と大文字は区別して認識される

